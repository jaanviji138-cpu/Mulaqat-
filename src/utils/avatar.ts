export function generateIndianProfile(genderPreference: 'male' | 'female' | 'random' = 'random') {
  let gender = genderPreference;
  if (gender === 'random') {
    gender = Math.random() > 0.5 ? 'male' : 'female';
  }

  const nameList = gender === 'male' ? INDIAN_MALE_NAMES : INDIAN_FEMALE_NAMES;
  const avatarList = gender === 'male' ? INDIAN_MALE_AVATARS : INDIAN_FEMALE_AVATARS;

  const displayName = nameList[Math.floor(Math.random() * nameList.length)];
  const photoURL = avatarList[Math.floor(Math.random() * avatarList.length)];
  const bio = INDIAN_BIOS[Math.floor(Math.random() * INDIAN_BIOS.length)];
  const age = Math.floor(20 + Math.random() * 8); // 20 to 27

  return {
    displayName,
    photoURL,
    gender,
    bio,
    age,
    country: 'India 🇮🇳'
  };
}

